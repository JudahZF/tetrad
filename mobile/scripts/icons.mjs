// Renders the unit's icons (tetrad-assets) into assets/icons/*.png and writes
// src/ui/icon-assets.ts, so the app and the unit draw the same glyphs.
// Run from mobile/: `pnpm icons`. Needs cargo.
import { Buffer } from "node:buffer";
import { execFileSync } from "node:child_process";
import { mkdirSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { deflateSync } from "node:zlib";

const here = dirname(fileURLToPath(import.meta.url));
const mobile = join(here, "..");
const repo = join(mobile, "..");
const out = join(mobile, "assets", "icons");

const lines = execFileSync(
  "cargo",
  ["run", "-q", "-p", "tetrad-assets", "--example", "icon_masks"],
  { cwd: repo, encoding: "utf8", maxBuffer: 64 * 1024 * 1024 },
)
  .trim()
  .split("\n");

const crcTable = Array.from({ length: 256 }, (_, n) => {
  let c = n;
  for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
  return c >>> 0;
});
const crc32 = (bytes) => {
  let c = 0xffffffff;
  for (const b of bytes) c = crcTable[(c ^ b) & 0xff] ^ (c >>> 8);
  return (c ^ 0xffffffff) >>> 0;
};
const chunk = (type, data) => {
  const head = Buffer.alloc(8);
  head.writeUInt32BE(data.length, 0);
  head.write(type, 4, "ascii");
  const crc = Buffer.alloc(4);
  crc.writeUInt32BE(crc32(Buffer.concat([head.subarray(4), data])), 0);
  return Buffer.concat([head, data, crc]);
};

/** White ink with the mask as alpha (grey + alpha PNG), tinted in the app. */
function png(side, alpha) {
  const rows = [];
  for (let y = 0; y < side; y++) {
    const row = Buffer.alloc(1 + side * 2);
    for (let x = 0; x < side; x++) {
      row[1 + x * 2] = 255;
      row[2 + x * 2] = alpha[y * side + x];
    }
    rows.push(row);
  }
  const ihdr = Buffer.alloc(13);
  ihdr.writeUInt32BE(side, 0);
  ihdr.writeUInt32BE(side, 4);
  ihdr[8] = 8; // bit depth
  ihdr[9] = 4; // grey + alpha
  return Buffer.concat([
    Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]),
    chunk("IHDR", ihdr),
    chunk("IDAT", deflateSync(Buffer.concat(rows), { level: 9 })),
    chunk("IEND", Buffer.alloc(0)),
  ]);
}

rmSync(out, { recursive: true, force: true });
mkdirSync(out, { recursive: true });
const names = [];
for (const line of lines) {
  const [name, sideText, leftText, topText, widthText, heightText, hex] = line.split(" ");
  const [side, left, top, width, height] = [sideText, leftText, topText, widthText, heightText].map(Number);
  const mask = Buffer.from(hex, "hex");
  // The mask may reach a little past the box; the box clips it, as on the unit.
  const alpha = new Uint8Array(side * side);
  for (let y = 0; y < height; y++) {
    for (let x = 0; x < width; x++) {
      const bx = x + left;
      const by = y + top;
      if (bx >= 0 && by >= 0 && bx < side && by < side) alpha[by * side + bx] = mask[y * width + x];
    }
  }
  writeFileSync(join(out, `${name}.png`), png(side, alpha));
  names.push(name);
}

const entries = names.map((n) => `  "${n}": require("../../assets/icons/${n}.png"),`).join("\n");
writeFileSync(
  join(mobile, "src", "ui", "icon-assets.ts"),
  `// Generated by scripts/icons.mjs from tetrad-assets. Do not edit.
export const iconAssets = {
${entries}
} as const;

export type IconName = keyof typeof iconAssets;
`,
);
console.log(`${names.length} icons in assets/icons`);
